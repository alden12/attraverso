/**
 * Source reference pointers in prose (`CTX-13`): where they are, and what text each one stands behind.
 *
 * A claim is followed by a pointer, `[ref r7k2]`, and the reference's sources live in `source_references`. This
 * module is the one parser every reader shares - the tools, `apm:check` and the viewer - so it is Node-free, like
 * `tickets.ts`: two parsers that split a body differently would make one claim stale in one place and fine in
 * another.
 *
 * **What a pointer covers is set by where it sits, never stored:**
 *
 * - **Inline, it covers the text before it** in the same markdown block, back to the previous pointer or the
 *   block's start - the footnote convention, a citation after its claim. A block is a paragraph, one list item,
 *   one table row, a heading, or a code block.
 * - **On its own line, it covers the whole group above it**: a paragraph, a whole list, a whole table, a code block.
 *   Pointer-only lines in between are skipped, so two sources can stand behind one table.
 *
 * **What is not a pointer:** anything inside a code span or a fenced block, so documentation of this syntax never
 * trips it; an escaped `\[ref`; one followed by `(`, which markdown reads as a link (`[ref docs](https://...)`), or
 * by `:` at the start of a line, a link definition; and only `[ref ` followed by a key opens one, so task boxes and
 * footnotes never do.
 * Indented code is not masked, deliberately: four-space list continuations are far commoner in these bodies.
 *
 * Deliberately a small line scanner rather than a markdown parser: the server has no markdown dependency at
 * runtime, and the few block shapes that matter here are easy to tell apart by their first characters.
 */

/** A key is short lowercase letters and digits, generated by the tool: never shaped like an item's ref. */
const KEY = "[a-z0-9]+";
/** How long an expanded pointer's detail may run: `get_item` keeps what it shows well under it, and the bound keeps a
 *  run of unclosed `[ref k:` from costing quadratic time on hostile input. */
const EXPANSION = "[^\\]\\n]{0,3000}";
/** `[ref key]`, or the expanded `[ref key: ...]` that `get_item` returns and an agent may send straight back. Not
 *  escaped, not followed by `(`, which makes it a link, and not followed by `:` when it starts its line (up to three
 *  spaces in), which makes it a link definition. A `]:` mid-sentence is prose (`CTX-17.3`: "linked from the guide
 *  [ref onb4]: ..." was refused as missing), so the colon only counts where markdown would read a definition. */
const POINTER = new RegExp(
  `(?<!\\\\)\\[ref (${KEY})(?::${EXPANSION})?\\](?!\\()(?!:(?<=^ {0,3}\\[ref ${KEY}(?::${EXPANSION})?\\]:))`,
  "gm",
);
/** `[ref ` not followed by a well-formed key and its close: a pointer someone meant to write and got wrong. */
const MALFORMED = new RegExp(`(?<!\\\\)\\[ref (?!${KEY}(?:\\]|:${EXPANSION}\\]))`, "g");

export interface Pointer {
  key: string;
  /** Where the pointer starts in the text, and its full written form (expanded or not). */
  at: number;
  written: string;
  /** The text it stands behind, normalised: what a source's `quoted_text` is compared against. */
  covers: string;
}

export interface PointerProblem {
  at: number;
  problem: string;
}

type BlockKind = "paragraph" | "list" | "table" | "heading" | "code";

interface Block {
  kind: BlockKind;
  /** Consecutive list items share a group, as do consecutive table rows: what an own-line pointer covers. */
  group: number;
  start: number;
  end: number;
}

/**
 * The comparison form of some covered text: whitespace collapsed, Unicode NFC, and trimmed of what surrounds a
 * claim rather than belonging to it - a list marker or heading hashes in front, a table's pipes, the punctuation
 * left at the start of a span by the previous pointer's sentence.
 */
export function normaliseClaim(text: string): string {
  return text
    .normalize("NFC")
    .replace(/^[ \t]*>[ \t]?/gm, "") // a blockquote's markers, so rewrapping a quote never reads as a change
    .replace(/\s+/g, " ")
    .replace(/^\s*(?:[-*+]|\d+[.)]|#{1,6})\s+/, "")
    .replace(/^[\s|.,;:!?)]+/, "")
    .replace(/[\s|]+$/, "")
    .trim();
}

/** A fence marker opening a line: three or more backticks or tildes. */
const fenceOf = (line: string): string | undefined => /^\s*(`{3,}|~{3,})/.exec(line)?.[1];
/** Whether `marker` closes a block opened by `fence`: the same character, at least as many of it. */
const closes = (fence: string, marker: string): boolean => marker[0] === fence[0] && marker.length >= fence.length;

/** The text with every code span and fenced block blanked to spaces, keeping offsets, so pointers in code vanish. */
function maskCode(text: string): string {
  const lines = text.split("\n");
  let fence: string | undefined;
  const masked = lines.map((line) => {
    const marker = fenceOf(line);
    if (fence === undefined && marker !== undefined) {
      fence = marker;
      return " ".repeat(line.length);
    }
    if (fence !== undefined) {
      if (marker !== undefined && closes(fence, marker)) fence = undefined;
      return " ".repeat(line.length);
    }
    return line;
  });
  // Then inline spans, on what is left, one paragraph at a time: a code span never crosses a blank line.
  return masked
    .join("\n")
    .split(/(\n[ \t]*\n)/)
    .map(maskSpans)
    .join("");
}

/**
 * Blank the inline code spans in one paragraph: a run of backticks closed by the next run of exactly the same
 * length. A run with no partner is literal text, and the scan carries on after it, as CommonMark has it - so a
 * stray backtick in prose ("the ` key") hides nothing after it.
 */
function maskSpans(paragraph: string): string {
  const runs = [...paragraph.matchAll(/`+/g)].map((m) => ({ at: m.index, length: m[0].length }));
  // Each run's next run of the same length, found in one pass from the end, so a paragraph of many unmatched
  // backticks costs linear time rather than a scan forward from every one of them.
  const nextSame: number[] = new Array(runs.length).fill(-1);
  const seen = new Map<number, number>();
  for (let i = runs.length - 1; i >= 0; i--) {
    nextSame[i] = seen.get(runs[i]!.length) ?? -1;
    seen.set(runs[i]!.length, i);
  }
  // Built once from its pieces, not re-sliced per span, which would be quadratic in a paragraph of many spans.
  const pieces: string[] = [];
  let last = 0;
  for (let i = 0; i < runs.length; i++) {
    const open = runs[i]!;
    const close = nextSame[i]!;
    if (close === -1) continue;
    const end = runs[close]!.at + open.length;
    pieces.push(paragraph.slice(last, open.at), " ".repeat(end - open.at));
    last = end;
    i = close;
  }
  return last === 0 ? paragraph : pieces.join("") + paragraph.slice(last);
}

/**
 * Split a text into blocks by its lines, with offsets into the original text. A paragraph runs until a blank line
 * or a line that opens a block of its own; a list item takes the unmarked lines after it (its lazy continuation);
 * a heading and a table row are one line each; a fenced block runs to its closing fence. Consecutive list items
 * share a group, even across a blank line, as do consecutive table rows, which is what an own-line pointer covers.
 */
function blocks(text: string): Block[] {
  const out: Block[] = [];
  let group = 0;
  let offset = 0;
  let open: Block | null = null;
  let fence: string | undefined;
  let afterBlank = false;
  for (const line of text.split("\n")) {
    const start = offset;
    const end = offset + line.length;
    offset = end + 1;
    const marker = fenceOf(line);
    if (fence !== undefined) {
      open!.end = end;
      if (marker !== undefined && closes(fence, marker)) {
        fence = undefined;
        open = null;
      }
      continue;
    }
    if (marker !== undefined) {
      fence = marker;
      open = { kind: "code", group: ++group, start, end };
      out.push(open);
      continue;
    }
    if (line.trim() === "") {
      open = null;
      afterBlank = true;
      continue;
    }
    const wasBlank = afterBlank;
    afterBlank = false;
    const kind: BlockKind | null = /^\s*#{1,6}\s/.test(line)
      ? "heading"
      : /^\s*\|/.test(line)
        ? "table"
        : /^\s*(?:[-*+]|\d+[.)])\s/.test(line)
          ? "list"
          : null;
    if (kind === null && open !== null && (open.kind === "paragraph" || open.kind === "list")) {
      open.end = end; // a wrapped paragraph, or a list item's continuation
      continue;
    }
    const last = out[out.length - 1];
    // A list continues across a blank line; a table ends at one.
    const joins = kind !== null && last !== undefined && last.kind === kind && (kind === "list" || !wasBlank);
    const block: Block = { kind: kind ?? "paragraph", group: joins ? last.group : ++group, start, end };
    out.push(block);
    open = block.kind === "heading" || block.kind === "table" ? null : block;
  }
  return out;
}

/**
 * Every pointer in `text`, with what it covers, and every problem a writer should be told about: a malformed
 * pointer, the same key twice, and a pointer line directly under a table row, which markdown reads as another row
 * of the table rather than a pointer below it (the blank line nobody sees).
 */
export function parsePointers(text: string): { readonly pointers: readonly Pointer[]; readonly problems: readonly PointerProblem[] } {
  // One write asks about the same text several times over - what to retire, what each new source covers, what an
  // edit changed, what to warn about - so the last few answers are kept. Frozen, because they are shared: a caller
  // that wants them sorted copies first, and one that forgets fails loudly instead of corrupting the next answer.
  const cached = parsed.get(text);
  if (cached !== undefined) return cached;
  const result = Object.freeze(parseUncached(text));
  Object.freeze(result.pointers);
  Object.freeze(result.problems);
  parsed.set(text, result);
  if (parsed.size > PARSE_CACHE) parsed.delete(parsed.keys().next().value!);
  return result;
}

/** How many texts' answers `parsePointers` keeps: enough for a write's before and after, its tool reply, and a
 *  read or two in between, without holding on to a whole plan's bodies. Oldest out first. */
const PARSE_CACHE = 16;
const parsed = new Map<string, { pointers: Pointer[]; problems: PointerProblem[] }>();

function parseUncached(text: string): { pointers: Pointer[]; problems: PointerProblem[] } {
  const masked = maskCode(text);
  const all = blocks(text);
  const pointers: Pointer[] = [];
  const problems: PointerProblem[] = [];
  const seen = new Set<string>();

  for (const match of masked.matchAll(MALFORMED)) {
    const snippet = text.slice(match.index, match.index + 16).split("\n")[0]!;
    problems.push({ at: match.index, problem: `"${snippet}" is not a pointer: write [ref <key>], where a key is lowercase letters and digits` });
  }

  /** The original text of [from, to) with its pointers taken out, normalised: what a pointer covers. Code stays
   *  in, since a claim can be about a command; only pointers, found in the masked copy, are removed. */
  const covered = (from: number, to: number): string => {
    let out = "";
    let last = from;
    for (const m of masked.slice(from, to).matchAll(POINTER)) {
      out += text.slice(last, from + m.index) + " ";
      last = from + m.index + m[0].length;
    }
    return normaliseClaim(out + text.slice(last, to));
  };

  all.forEach((block, index) => {
    const inBlock = [...masked.slice(block.start, block.end).matchAll(POINTER)].map((m) => ({ key: m[1]!, at: block.start + m.index, written: m[0] }));
    if (inBlock.length === 0) return;
    const ownLine = normaliseClaim(masked.slice(block.start, block.end).replace(POINTER, " ")) === "";
    if (ownLine) {
      // The nearest block above that is not itself only pointers: what this line stands behind.
      const above = all
        .slice(0, index)
        .reverse()
        .find((candidate) => candidate.kind === "code" || normaliseClaim(masked.slice(candidate.start, candidate.end).replace(POINTER, " ")) !== "");
      // Markdown continues a table through the very next line, so a pointer there is a row, not a citation below.
      if (above !== undefined && above.kind === "table" && !/\n\s*\n/.test(text.slice(above.end, block.start))) {
        problems.push({ at: inBlock[0]!.at, problem: `put a blank line between the table and [ref ${inBlock[0]!.key}], or markdown reads it as another row` });
      }
      const groupBlocks = above === undefined ? [] : all.filter((candidate) => candidate.group === above.group && candidate.end <= block.start);
      const covers = groupBlocks.map((b) => covered(b.start, b.end)).filter(Boolean).join(" ");
      for (const p of inBlock) pointers.push({ ...p, covers: normaliseClaim(covers) });
      return;
    }
    let from = block.start;
    for (const p of inBlock) {
      // A pointer alone on a line straight under a list item is that item's lazy continuation to markdown, so it
      // would cover the last item only, not the list: the same blank line the table case needs.
      const lineStart = text.lastIndexOf("\n", p.at - 1) + 1;
      const lineEnd = text.indexOf("\n", p.at) === -1 ? text.length : text.indexOf("\n", p.at);
      if (block.kind === "list" && lineStart > block.start && normaliseClaim(masked.slice(lineStart, lineEnd).replace(POINTER, " ")) === "") {
        problems.push({ at: p.at, problem: `put a blank line between the list and [ref ${p.key}], or markdown reads it as part of the last item` });
      }
      pointers.push({ ...p, covers: covered(from, p.at) });
      from = p.at + p.written.length;
    }
  });

  for (const p of pointers) {
    if (p.covers === "") problems.push({ at: p.at, problem: `[ref ${p.key}] has nothing before it to stand behind: put it straight after its claim` });
  }

  for (const p of pointers) {
    if (seen.has(p.key)) problems.push({ at: p.at, problem: `[ref ${p.key}] appears twice: a key stands behind one claim` });
    seen.add(p.key);
  }
  return { pointers, problems };
}

/** The text with every expanded pointer reduced to its bare form, `[ref key: ...]` to `[ref key]`, outside code -
 *  what is stored, whatever `get_item` returned and the writer sent back. */
export function bareForm(text: string): string {
  const masked = maskCode(text);
  let out = "";
  let last = 0;
  for (const match of masked.matchAll(POINTER)) {
    out += text.slice(last, match.index) + `[ref ${match[1]}]`;
    last = match.index + match[0].length;
  }
  return out + text.slice(last);
}

/** A `code` source's detail, parsed: lines of a file at a commit, which never change, so the evidence cannot rot. */
export interface CodeRef {
  path: string;
  from: number;
  to: number;
  column?: number;
  commit: string;
}

/**
 * `path:line[-line][:column]@commit`, e.g. `packages/core/src/domain/items.ts:308-339@345a746`. Repo-relative rather
 * than a hosting provider's URL, so it works in a private repo, a fork and the open export alike; a viewer can still
 * make a link of it where it knows the host. Null when the detail is not one, which the writing tool refuses.
 */
export function parseCodeRef(detail: string): CodeRef | null {
  const match = /^([^\s:@][^\s:@]*):([1-9]\d*)(?:-([1-9]\d*))?(?::([1-9]\d*))?@([0-9a-f]{7,40})$/.exec(detail.trim());
  if (match === null) return null;
  // Repo-relative and inside the repo: no `..` step, no leading `/`, no backslash. git refuses a path outside the
  // checkout partway through a batch, which would cost every other code source on the same read its answer.
  if (match[1]!.startsWith("/") || match[1]!.includes("\\") || match[1]!.split("/").includes("..")) return null;
  const from = Number(match[2]);
  const to = match[3] === undefined ? from : Number(match[3]);
  if (to < from) return null;
  return { path: match[1]!, from, to, ...(match[4] === undefined ? {} : { column: Number(match[4]) }), commit: match[5]! };
}
